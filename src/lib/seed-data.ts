// Helper to create full menu items with standard image paths
const makeItem = (
  id: string,
  catId: string,
  slug: string,
  name_en: string,
  name_sw: string,
  price_kes: number,
  description_en: string,
  description_sw: string,
  opts: {
    prep?: number;
    spice?: number;
    is_available?: boolean;
    is_featured?: boolean;
    is_chefs_pick?: boolean;
    dietary?: Partial<MenuItem['dietary_flags']>;
    allergens?: string[];
    sort?: number;
  } = {}
): MenuItem => {
  const dietary = {
    vegetarian: false,
    vegan: false,
    halal: true,
    gluten_free: false,
    dairy_free: false,
    nut_free: true,
    ...opts.dietary,
  };

  const imagePath = `/images/menu/${slug}.webp`;

  return {
    id,
    category_id: catId,
    name_en,
    name_sw,
    description_en,
    description_sw,
    price_kes,
    usd_override: null,
    prep_minutes: opts.prep ?? 15,
    spice_level: opts.spice ?? 0,
    dietary_flags: dietary,
    allergens: opts.allergens ?? [],
    calories: null,
    is_available: opts.is_available ?? true,
    is_featured: opts.is_featured ?? false,
    is_chefs_pick: opts.is_chefs_pick ?? false,
    sort_order: opts.sort ?? 0,
    deleted_at: null,
    created_at: '2026-10-16T00:00:00Z',
    updated_at: '2026-10-16T00:00:00Z',
    images: [
      {
        id: `img-${id}`,
        item_id: id,
        storage_path: imagePath,
        alt_text: `Editorial culinary photograph of freshly prepared ${name_en} at Crown Hotels Nairobi`,
        is_primary: true,
        width: 1200,
        height: 900,
        variants: {
          '400w': `/images/menu/variants/${slug}-400w.webp`,
          '800w': `/images/menu/variants/${slug}-800w.webp`,
          '1200w': imagePath,
        },
        created_at: '2026-10-16T00:00:00Z',
      },
    ],
  };
};

