async function testAll() {
  console.log(`Testing ${Object.keys(PHOTO_URLS).length} food image URLs...`);
  const failed: string[] = [];

  for (const [slug, url] of Object.entries(PHOTO_URLS)) {
    try {
      const res = await fetch(url, { method: 'HEAD' });
      if (res.status === 200) {
        process.stdout.write('.');
      } else {
        console.log(`\nFAIL: ${slug} -> ${res.status}`);
        failed.push(slug);
      }
    } catch (e: any) {
      console.log(`\nERROR: ${slug} -> ${e.message}`);
      failed.push(slug);
    }
  }

  console.log(`\nDone! Total URLs: ${Object.keys(PHOTO_URLS).length}, Failed: ${failed.length}`);
  if (failed.length > 0) {
    console.log('Failed slugs:', failed);
  }
}

testAll();

